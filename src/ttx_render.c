static const uint8_t *get_latin1_glyph(uint8_t ch, uint8_t tmp[8]) {
    if (ch >= 0x20 && ch <= 0x7F) {
        return g_font8x8[ch - 0x20];
    }
    /* Special ISO-8859-1 European teletext characters */
    static const uint8_t gl_Auml[8]  = {0x24,0x00,0x3C,0x42,0x7E,0x42,0x42,0x00}; /* Ä */
    static const uint8_t gl_Ouml[8]  = {0x24,0x00,0x3C,0x42,0x42,0x42,0x3C,0x00}; /* Ö */
    static const uint8_t gl_Uuml[8]  = {0x24,0x00,0x42,0x42,0x42,0x42,0x3C,0x00}; /* Ü */
    static const uint8_t gl_auml[8]  = {0x24,0x00,0x3C,0x02,0x3E,0x42,0x3E,0x00}; /* ä */
    static const uint8_t gl_ouml[8]  = {0x24,0x00,0x3C,0x42,0x42,0x42,0x3C,0x00}; /* ö */
    static const uint8_t gl_uuml[8]  = {0x24,0x00,0x42,0x42,0x42,0x42,0x3E,0x00}; /* ü */
    static const uint8_t gl_szlig[8] = {0x38,0x44,0x48,0x44,0x44,0x58,0x40,0x00}; /* ß */
    static const uint8_t gl_deg[8]   = {0x18,0x24,0x18,0x00,0x00,0x00,0x00,0x00}; /* ° */
    static const uint8_t gl_sect[8]  = {0x3C,0x40,0x38,0x44,0x38,0x04,0x78,0x00}; /* § */
    static const uint8_t gl_laquo[8] = {0x00,0x14,0x28,0x50,0x28,0x14,0x00,0x00}; /* « */
    static const uint8_t gl_raquo[8] = {0x00,0x50,0x28,0x14,0x28,0x50,0x00,0x00}; /* » */

    switch (ch) {
        case 0xA0: return g_font8x8[0];
        case 0xA7: return gl_sect;
        case 0xAB: return gl_laquo;
        case 0xB0: return gl_deg;
        case 0xBB: return gl_raquo;
        case 0xC4: return gl_Auml;
        case 0xD6: return gl_Ouml;
        case 0xDC: return gl_Uuml;
        case 0xDF: return gl_szlig;
        case 0xE4: return gl_auml;
        case 0xF6: return gl_ouml;
        case 0xFC: return gl_uuml;
        case 0xE0: case 0xE1: case 0xE2: return g_font8x8['a' - 0x20];
        case 0xE7: return g_font8x8['c' - 0x20];
        case 0xE8: case 0xE9: case 0xEA: case 0xEB: return g_font8x8['e' - 0x20];
        case 0xEC: case 0xED: case 0xEE: case 0xEF: return g_font8x8['i' - 0x20];
        case 0xF2: case 0xF3: case 0xF4: return g_font8x8['o' - 0x20];
        case 0xF9: case 0xFA: case 0xFB: return g_font8x8['u' - 0x20];
        default:
            (void)tmp;
            return g_font8x8['?' - 0x20];
    }
}

void ttx_render_init(TtxRenderer *rnd) {
    memset(rnd, 0, sizeof(*rnd));
    rnd->flash_on = true;
    rnd->reveal = false;
    rnd->hover_row = -1;
    rnd->hover_col = -1;
}

static void render_cell_mosaic(uint32_t *fb, int x0, int y0, uint8_t m6, bool sep, uint32_t fg, uint32_t bg) {
    /* 2 columns x 3 rows of sixels inside 16x20 cell */
    static const int cx[2][2] = {{0, 8}, {8, 16}};
    static const int cy[3][2] = {{0, 7}, {7, 13}, {13, 20}};

    for (int py = 0; py < TTX_CELL_H; py++) {
        uint32_t *row_ptr = fb + (y0 + py) * TTX_FB_W + x0;
        for (int px = 0; px < TTX_CELL_W; px++) {
            row_ptr[px] = bg;
        }
    }

    int pad = sep ? 1 : 0;
    for (int sy = 0; sy < 3; sy++) {
        for (int sx = 0; sx < 2; sx++) {
            int bit = sy * 2 + sx;
            if (m6 & (1 << bit)) {
                int rx0 = cx[sx][0] + pad;
                int rx1 = cx[sx][1] - pad;
                int ry0 = cy[sy][0] + pad;
                int ry1 = cy[sy][1] - pad;
                for (int py = ry0; py < ry1; py++) {
                    uint32_t *row_ptr = fb + (y0 + py) * TTX_FB_W + x0;
                    for (int px = rx0; px < rx1; px++) {
                        row_ptr[px] = fg;
                    }
                }
            }
        }
    }
}

static void render_cell_char(uint32_t *fb, int x0, int y0, uint8_t ch, uint32_t fg, uint32_t bg, bool double_h, bool underline) {
    uint8_t tmp[8];
    const uint8_t *glyph = get_latin1_glyph(ch, tmp);

    /* Fill background */
    for (int py = 0; py < TTX_CELL_H; py++) {
        uint32_t *row_ptr = fb + (y0 + py) * TTX_FB_W + x0;
        for (int px = 0; px < TTX_CELL_W; px++) {
            row_ptr[px] = bg;
        }
    }

    int y_off = 2;
    int scale_y = double_h ? 4 : 2;
    for (int gy = 0; gy < 8; gy++) {
        uint8_t bits = glyph[gy];
        for (int sy = 0; sy < scale_y; sy++) {
            int py = y_off + gy * scale_y + sy;
            if (py >= TTX_CELL_H && !double_h) continue;
            if (y0 + py >= TTX_FB_H) continue;
            uint32_t *row_ptr = fb + (y0 + py) * TTX_FB_W + x0;
            for (int gx = 0; gx < 8; gx++) {
                if (bits & (0x80 >> gx)) {
                    row_ptr[gx * 2] = fg;
                    row_ptr[gx * 2 + 1] = fg;
                }
            }
        }
    }

    if (underline && y0 + TTX_CELL_H - 2 < TTX_FB_H) {
        uint32_t *row_ptr = fb + (y0 + TTX_CELL_H - 2) * TTX_FB_W + x0;
        for (int px = 0; px < TTX_CELL_W; px++) {
            row_ptr[px] = fg;
        }
    }
}

void ttx_render_page(TtxRenderer *rnd, const TtxPage *pg) {
    if (!pg) return;

    for (int r = 0; r < TTX_ROWS; r++) {
        for (int c = 0; c < TTX_COLS; c++) {
            const TtxCell *cell = &pg->cells[r][c];
            uint32_t fg = g_ttx_palette[cell->fg & 7];
            uint32_t bg = g_ttx_palette[cell->bg & 7];

            bool hidden = ((cell->attrs & TTX_ATTR_CONCEAL) && !rnd->reveal) ||
                          ((cell->attrs & TTX_ATTR_FLASH) && !rnd->flash_on);

            bool hovered = (rnd->hover_link != 0 && cell->link_page == rnd->hover_link);
            if (hovered) {
                uint32_t tmp = fg;
                fg = bg;
                bg = tmp;
                if (fg == bg) fg = 0xFF000000;
            }

            int x0 = c * TTX_CELL_W;
            int y0 = r * TTX_CELL_H;

            if (hidden) {
                render_cell_char(rnd->pixels, x0, y0, ' ', fg, bg, false, false);
            } else if (cell->attrs & TTX_ATTR_MOSAIC) {
                render_cell_mosaic(rnd->pixels, x0, y0, cell->ch & 0x3F,
                                   (cell->attrs & TTX_ATTR_SEPARATED) != 0, fg, bg);
            } else {
                bool ul = (cell->link_page != 0 && hovered);
                render_cell_char(rnd->pixels, x0, y0, cell->ch, fg, bg,
                                 (cell->attrs & TTX_ATTR_DOUBLE_H) != 0, ul);
            }
        }
    }
}

bool ttx_render_hit_test(int x, int y, int canvas_w, int canvas_h, int *out_row, int *out_col) {
    if (canvas_w <= 0 || canvas_h <= 0 || x < 0 || y < 0 || x >= canvas_w || y >= canvas_h) {
        return false;
    }
    int col = (x * TTX_COLS) / canvas_w;
    int row = (y * TTX_ROWS) / canvas_h;
    if (col < 0) col = 0;
    if (col >= TTX_COLS) col = TTX_COLS - 1;
    if (row < 0) row = 0;
    if (row >= TTX_ROWS) row = TTX_ROWS - 1;
    *out_row = row;
    *out_col = col;
    return true;
}

bool ttx_export_bmp(const TtxRenderer *rnd, const char *filepath) {
    if (!rnd || !filepath) return false;
    FILE *f = fopen(filepath, "wb");
    if (!f) return false;

    uint32_t row_bytes = TTX_FB_W * 3;
    uint32_t img_size = row_bytes * TTX_FB_H;
    uint32_t file_size = 54 + img_size;

    uint8_t hdr[54] = {0};
    hdr[0] = 'B'; hdr[1] = 'M';
    hdr[2] = (uint8_t)(file_size);
    hdr[3] = (uint8_t)(file_size >> 8);
    hdr[4] = (uint8_t)(file_size >> 16);
    hdr[5] = (uint8_t)(file_size >> 24);
    hdr[10] = 54;
    hdr[14] = 40;
    hdr[18] = (uint8_t)(TTX_FB_W);
    hdr[19] = (uint8_t)(TTX_FB_W >> 8);
    hdr[22] = (uint8_t)(TTX_FB_H);
    hdr[23] = (uint8_t)(TTX_FB_H >> 8);
    hdr[26] = 1;
    hdr[28] = 24;

    fwrite(hdr, 1, 54, f);

    uint8_t line[TTX_FB_W * 3];
    for (int y = TTX_FB_H - 1; y >= 0; y--) {
        const uint32_t *src = rnd->pixels + y * TTX_FB_W;
        for (int x = 0; x < TTX_FB_W; x++) {
            uint32_t p = src[x];
            line[x * 3 + 0] = (uint8_t)(p & 0xFF);         /* B */
            line[x * 3 + 1] = (uint8_t)((p >> 8) & 0xFF);  /* G */
            line[x * 3 + 2] = (uint8_t)((p >> 16) & 0xFF); /* R */
        }
        fwrite(line, 1, row_bytes, f);
    }

    fclose(f);
    return true;
}
